subcategory_map = {
    "jafacility20": {"categories": jafacility20, "num": jafacility20_num},
    "jaflower30": {"categories": jaflower30, "num": jaflower30_num},
    "jafood101": {"categories": jafood101, "num": jafood101_num},
    "jalandmark10": {"categories": jalandmark10, "num": jalandmark10_num},
}

from datasets import load_dataset

dataset = load_dataset(
    "speed/japanese-image-classification-evaluation-dataset",
    split="train",
    num_proc=32,
    trust_remote_code=True,
)


def get_subcategory(category):
    for subcategory, info in subcategory_map.items():
        if category in info["categories"]:
            return subcategory
    return None


# add subcategory column
dataset = dataset.map(
    lambda x: {"subcategory": get_subcategory(x["category"])},
    num_proc=32,
)
print(dataset[0])
